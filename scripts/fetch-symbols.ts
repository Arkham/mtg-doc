/**
 * Downloads Scryfall's mana and card symbols into public/symbols and writes src/symbols.ts, so the
 * app serves them itself (cached, offline-friendly) instead of hot-linking svgs.scryfall.io.
 * Re-run when new sets add symbols: `pnpm symbols`.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public/symbols");
const HEADERS = { "User-Agent": "mtg-doc/1.0", Accept: "application/json" };

interface ScryfallSymbol {
  symbol: string;
  svg_uri: string | null;
}

const res = await fetch("https://api.scryfall.com/symbology", { headers: HEADERS });
if (!res.ok) throw new Error(`Scryfall symbology failed: ${res.status}`);
const { data } = (await res.json()) as { data: ScryfallSymbol[] };

await fs.mkdir(OUT, { recursive: true });
const files: Record<string, string> = {};
for (const s of data) {
  if (!s.svg_uri) continue;
  const file = path.basename(new URL(s.svg_uri).pathname, ".svg");
  const svg = await fetch(s.svg_uri, { headers: { "User-Agent": HEADERS["User-Agent"] } });
  if (!svg.ok) throw new Error(`${s.svg_uri}: ${svg.status}`);
  await fs.writeFile(path.join(OUT, `${file}.svg`), Buffer.from(await svg.arrayBuffer()));
  files[s.symbol.slice(1, -1)] = file;
  // Scryfall asks for 50-100ms between requests.
  await new Promise((r) => setTimeout(r, 80));
}

const entries = Object.entries(files)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([sym, file]) => `  ${JSON.stringify(sym)}: ${JSON.stringify(file)},`)
  .join("\n");
await fs.writeFile(
  path.join(ROOT, "src/symbols.ts"),
  `// Generated by scripts/fetch-symbols.ts. Do not edit by hand.\n\n/** Symbol text (without braces) → file name in public/symbols. */\nexport const SYMBOL_FILES: Record<string, string> = {\n${entries}\n};\n`,
);
execFileSync("pnpm", ["exec", "prettier", "--write", "src/symbols.ts"], { cwd: ROOT });
console.log(`Saved ${Object.keys(files).length} symbols to public/symbols`);
